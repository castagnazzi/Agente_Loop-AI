const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('loop', {
  // pet
  dragStart: () => ipcRenderer.send('pet:drag-start'),
  dragMove: (dx, dy) => ipcRenderer.send('pet:drag-move', dx, dy),
  dragEnd: () => ipcRenderer.send('pet:drag-end'),
  petWheel: (dy) => ipcRenderer.send('pet:wheel', dy),
  petClick: () => ipcRenderer.send('pet:click'),
  petMenu: () => ipcRenderer.send('pet:menu'),
  // chat
  send: (text, files) => ipcRenderer.invoke('chat:send', text, files),
  cancel: () => ipcRenderer.send('chat:cancel'),
  newSession: () => ipcRenderer.send('chat:new'),
  hideChat: () => ipcRenderer.send('chat:hide'),
  openSettings: () => ipcRenderer.send('settings:open'),
  onEvent: (cb) => ipcRenderer.on('chat:event', (_e, ev) => cb(ev)),
  pathForFile: (f) => webUtils.getPathForFile(f),
  openPath: (p) => ipcRenderer.send('chat:open-path', p),
  exportHtml: (data) => ipcRenderer.invoke('chat:export-html', data),
  pickFiles: () => ipcRenderer.invoke('chat:pick-files'),
  sessionList: () => ipcRenderer.invoke('session:list'),
  sessionOpen: (id) => ipcRenderer.invoke('session:open', id),
  sessionDelete: (id) => ipcRenderer.invoke('session:delete', id),
  sessionCurrent: () => ipcRenderer.invoke('session:current'),
  changesList: () => ipcRenderer.invoke('changes:list'),
  changesUndo: (id) => ipcRenderer.invoke('changes:undo', id),
  auditExport: () => ipcRenderer.invoke('audit:export'),
  savePastedImage: (b64, ext) => ipcRenderer.invoke('chat:save-pasted-image', b64, ext),
  // settings
  settingsZoom: (d) => ipcRenderer.invoke('settings:zoom', d),
  onSettingsZoom: (cb) => ipcRenderer.on('settings:zoom', (_e, z) => cb(z)),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  remoteAnalyze: (url) => ipcRenderer.invoke('remote:analyze', url),
  remoteInstall: (id, keys, hasPlugin) => ipcRenderer.invoke('remote:install', id, keys, hasPlugin),
  extList: () => ipcRenderer.invoke('ext:list'),
  extAdd: (kind, mode) => ipcRenderer.invoke('ext:add', kind, mode),
  extRemove: (kind, id) => ipcRenderer.invoke('ext:remove', kind, id),
  extToggle: (kind, id, on) => ipcRenderer.invoke('ext:toggle', kind, id, on),
  extOpenFolder: (kind) => ipcRenderer.send('ext:open-folder', kind),
  fetchModels: (provider) => ipcRenderer.invoke('settings:fetch-models', provider),
  importOpencode: () => ipcRenderer.invoke('settings:import-opencode'),
  replyPermission: (id, reply) => ipcRenderer.send('permission:reply', id, reply),
});
